def material_type_name(h):
    """shader_id_hash → 主材质类型名；无则 None。"""
    return MATERIAL_TYPE_NAMES.get(h & 0xFFFFFFFF)


def texture_slot_name(h):
    """Tex_Set.t → 贴图槽名；无则 None。"""
    return TEXTURE_SLOT_NAMES.get(h & 0xFFFFFFFF)


# ─────────────────────────────────────────────────────────────────────────────
# MATERIAL 块结构化只读解析（不参与序列化/导出，仅供 UI 标注）
#
# 结构（见 refs/EFX_Crimson.bt 的 Material/Tex_Block/Tex_Set，已 116/116 验证）：
#   data_bytes: int64 unkn00 + int block_count
#     Tex_Block × block_count:
#       u32 material_name_hash + u32 shader_id_hash + u32 unkn03 + int set_count
#       Tex_Set × set_count:  u32 set + i32 unkn0 + u32 t + u32 type  (+ 按 type 的 payload)
#         type 0x80: u32 head + u32 NULL + int path_len + char path[path_len]  ← 贴图路径
#         type 0x06: int64 + int            (12B)
#         type 0x03/0x0A/0x0C: u32[3]       (12B)
#         type 0x15: float[6]               (24B)
# ─────────────────────────────────────────────────────────────────────────────

import struct as _struct

_SET_EXTRA = {0x06: 12, 0x03: 12, 0x0A: 12, 0x0C: 12, 0x15: 24}


def parse_material(data_bytes):
    """把 MATERIAL 块 data_bytes 解析成结构化只读摘要；失败返回 None（UI 回退 opaque）。

    返回 dict：
      {'blocks': [ {'name_hash':int, 'shader_hash':int, 'type_name':str|None,
                    'sets': [ {'t':int, 'slot':str|None, 'type':int,
                               'path':str|None}, ... ] }, ... ] }
    仅含 type 0x80 的 set 带 path；其余 set 记录 t/slot/type 但 path=None。
    """
    d = data_bytes
    try:
        o = 0
        _unkn00 = _struct.unpack_from('<q', d, o)[0]; o += 8
        block_count = _struct.unpack_from('<i', d, o)[0]; o += 4
        if not (0 <= block_count < 4096):
            return None
        blocks = []
        for _ in range(block_count):
            name_hash = _struct.unpack_from('<I', d, o)[0]
            shader_hash = _struct.unpack_from('<I', d, o + 4)[0]
            set_count = _struct.unpack_from('<i', d, o + 12)[0]
            o += 16
            if not (0 <= set_count < 65536):
                return None
            sets = []
            for _ in range(set_count):
                t = _struct.unpack_from('<I', d, o + 8)[0]
                typ = _struct.unpack_from('<I', d, o + 12)[0]
                o += 16
                path = None
                if typ == 0x80:
                    plen = _struct.unpack_from('<i', d, o + 8)[0]
                    o += 12
                    raw = d[o:o + plen]
                    o += plen
                    path = raw.split(b'\x00')[0].decode('latin1') or None
                elif typ in _SET_EXTRA:
                    o += _SET_EXTRA[typ]
                else:
                    return None  # 未知 set type → 放弃（保守）
                sets.append({
                    't': t,
                    'slot': texture_slot_name(t),
                    'type': typ,
                    'path': path,
                })
            blocks.append({
                'name_hash': name_hash,
                'shader_hash': shader_hash,
                'type_name': material_type_name(shader_hash),
                'sets': sets,
            })
        return {'blocks': blocks}
    except Exception:
        return None
